# Program to demonstrate different Python data types

# Numeric Data Types
a = 10             
b = 10.5           
c = 2 + 3j         

# String Data Type
name = "Kunjal"     

# Sequence Data Types
my_list = [10, 20, 30]       
my_tuple = (10, 20, 30)     
my_range = range(1, 4)       

# Mapping Data Type
student = {"name": "Kunjal", "age": 20}   

# Boolean Data Type
is_student = True          

# Set Data Type
my_set = {10, 20, 30}      

# Display all values
print("Integer :", a)
print("Float   :", b)
print("Complex :", c)
print("String  :", name)
print("List    :", my_list)
print("Tuple   :", my_tuple)
print("Range   :", list(my_range))
print("Dictionary :", student)
print("Boolean :", is_student)
print("Set     :", my_set)
