# List, Tuple, Dictionary, Boolean and Set

# List
student_list = ["Kunjal", "Dev", "Raj"]
print("List :", student_list)

# Tuple
marks = (80, 75, 90)
print("Tuple :", marks)

# Dictionary
student = {
    "Name": "Kunjal",
    "Age": 20,
    "Course": "Python"
}
print("Dictionary :", student)

# Set
subjects = {"Python", "DBMS", "Java", "Python"}
print("Set :", subjects)
