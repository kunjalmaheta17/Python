# Write a program to perform mathematical operations using math module. 

import math
num = float(input("Enter a number: "))

print("Square root:", math.sqrt(num))
print("Power (square):", math.pow(num, 2))
print("Absolute value:", math.fabs(num))
print("Ceiling value:", math.ceil(num))
print("Floor value:", math.floor(num))
print("Factorial:", math.factorial(int(num)))
print("Sine:", math.sin(num))
print("Cosine:", math.cos(num))
print("Tangent:", math.tan(num))
print("Logarithm:", math.log(num))
