# Write a program to illustrate the use of different data types and type casting.

i=10
flt=10.5
text="Hiii"
bool1=True

print("int :",i,type(i))
print("float :",flt,type(flt)) 
print("text :",text,type(text))
print("bool :",bool1,type(bool1))
print()
print("Type casting")

a=20
b=float(a)
c=str(b)
d=bool(c)

print("Integer to float :",b,type(b))
print("Float to String :",c,type(c))
print("String to Bool :",d,type(d))





